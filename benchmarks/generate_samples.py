import torch
import tiktoken
import sys
import os

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from model import GPTModel
from generate import generate, token_ids_to_text, text_to_token_ids

def main():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    checkpoint_path = "../checkpoints/final_model.pth"
    print(f"Loading {checkpoint_path}...")
    checkpoint = torch.load(checkpoint_path, map_location=device)
    config = checkpoint["config"]
    
    model = GPTModel(config)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.to(device)
    model.eval()

    tokenizer = tiktoken.get_encoding("gpt2")
    
    prompts = [
        "The most important scientific discovery of the 20th century",
        "As the spaceship approached the black hole,",
        "The recipe for a perfect chocolate cake requires"
    ]
    
    md_content = "# Qualitative Generation Samples\n\n"
    md_content += "Samples generated by the ~30M parameter model trained on 50K documents of FineWeb-Edu.\n"
    md_content += "Settings: `temperature=0.7`, `top_k=50`, `max_new_tokens=40`.\n\n"
    
    print("\n" + "="*60)
    print("QUALITATIVE SAMPLES (Temp=0.7, Top-K=50)")
    print("="*60 + "\n")
    
    for prompt in prompts:
        encoded = text_to_token_ids(prompt, tokenizer).to(device)
        output_ids = generate(
            model=model, 
            idx=encoded, 
            max_new_tokens=40, 
            context_size=config["context_length"], 
            temperature=0.7, 
            top_k=50
        )
        text = token_ids_to_text(output_ids, tokenizer)
        print(f"PROMPT: {prompt}")
        print(f"OUTPUT:\n{text}\n")
        print("-" * 60 + "\n")
        
        md_content += f"**Prompt:** *{prompt}*\n\n"
        md_content += f"> {text}\n\n"
        md_content += "---\n\n"

    with open("qualitative_samples.md", "w") as f:
        f.write(md_content)
        
    print("Samples saved to benchmarks/qualitative_samples.md")

if __name__ == "__main__":
    main()
